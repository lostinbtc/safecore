// Uses a disposable browser profile. Screenshots contain demo data only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('./browser-helper.cjs');
const phrase = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about';
const password = 'Public-test-password-123';
const store = 'whippet.dev.encrypted.v1';
const output = path.resolve(__dirname, '../test-results');
fs.mkdirSync(output, {recursive:true});
(async () => {
  const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome', headless:true});
  try {
    for (const [name, size] of [['desktop',{width:1440,height:1050}],['mobile',{width:390,height:844}]]) {
      const context = await browser.newContext({viewport:size, acceptDownloads:true});
      await require('./empty_network.cjs')(context);
      const page = await context.newPage();
      await page.clock.install();
      const errors = [], external = [];
      page.on('pageerror', e => errors.push(e.message));
      page.on('console', m => {if (m.type() === 'error') errors.push(m.text());});
      page.on('request', req => { if (!req.url().startsWith('http://localhost:8787/') && !req.url().startsWith('data:') && !req.url().startsWith('blob:')) external.push(req.url()); });
      await page.goto('http://localhost:8787/');
      assert.equal(await page.title(), 'SafeCore · Multi-coin wallet');
      assert.equal(await page.locator('.mobile-brand').innerText(), 'SafeCore');
      assert.equal(await page.locator('#mode-pill').count(),0);
      assert.doesNotMatch(await page.locator('.topbar').innerText(),/preview mode|development wallet/i);
      assert.ok(await page.locator('.mobile-brand img').evaluate(el => el.complete && el.naturalWidth > 0));
      await page.locator('.holdings').waitFor();
      assert.equal(await page.locator('.holding-row').count(),3);
      assert.equal(await page.locator('#home-coin, .home-balance, .home-actions').count(),0);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
      assert.ok(await page.locator('.app-shell').evaluate(el=>el.getBoundingClientRect().width<=430));
      assert.ok(await page.locator('.bottom-navigation').evaluate(el=>Math.abs(el.getBoundingClientRect().bottom-innerHeight)<2));
      assert.match(await page.locator('[data-overview-coin=wht] .holding-balance').innerText(),/\*/);
      await page.screenshot({path:path.join(output,name+'-overview.png'),fullPage:true});
      await page.locator('[data-nav=receive]').click();
      await page.locator('#receive-coin').click();await page.locator('[data-coin="wht"]').click();
      await page.getByRole('heading',{name:'No payment address yet'}).waitFor();
      assert.equal(await page.locator('#qr canvas').count(), 0);
      await page.locator('#receive-setup').click();
      await page.locator('[data-setup="import"]').click();
      await page.locator('[data-restore-word="0"]').fill(phrase);await page.locator('#restore-done').click();
      await page.locator('#restore-options > summary').click();
      await page.locator('#use-passphrase').check();
      await page.locator('#passphrase').fill('TREZOR');
      await page.locator('#password-lock').check();
      await page.locator('#password').fill(password);
      await page.locator('#confirm').fill(password);
      assert.equal(await page.locator('#ack').count(),0);
      await page.locator('#submit-setup').click();
      await page.waitForFunction(() => document.documentElement.dataset.walletState === 'unlocked');
      assert.equal(await page.locator('.demo-label').count(), 0);
      await page.locator('[data-nav=receive]').click();await page.locator('#receive-coin').click();await page.locator('[data-coin="wht"]').click();await page.locator('#address').waitFor();
      await page.clock.runFor(4001);await page.locator('[data-nav="wallet"]').click();
      await page.waitForFunction(()=>document.querySelector('[data-overview-coin=wht] .holding-balance')?.textContent==='0 WHT');
      assert.equal(await page.getByRole('link',{name:'Enable live testing',exact:true}).count(),0);
      const raw = await page.evaluate(key => localStorage.getItem(key), store);
      assert.ok(raw && !raw.includes('abandon') && !raw.includes('TREZOR') && !raw.includes(password));
      await page.locator('[data-nav=receive]').click();
      await page.locator('#receive-coin').click();await page.locator('[data-coin="wht"]').click();
      await page.locator('#address').waitFor();
      const originalAddress = await page.locator('#address').textContent();
      assert.ok(originalAddress.length > 25);
      assert.equal(await page.locator('#qr canvas').count(), 1);
      await page.locator('[data-nav="security"]').click();
      const downloadEvent = page.waitForEvent('download');
      await page.locator('.wallets-shortcut').click();
      await page.locator('.saved-wallet:has([data-open-wallet]:disabled) > summary').click();
      await page.locator('.saved-wallet:has([data-open-wallet]:disabled) [data-export-wallet]').click();
      const download = await downloadEvent;
      const downloaded = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
      assert.deepEqual(downloaded, JSON.parse(raw));
      await page.reload();
      await page.waitForFunction(() => document.documentElement.dataset.walletState === 'locked');
      await page.locator('#lock').click();
      await page.locator('#unlock-password').fill('Incorrect-password-123');
      await page.locator('#unlock-submit').click();
      await page.locator('#error').waitFor({state:'visible'});
      assert.match(await page.locator('#error').textContent(), /Incorrect password/);
      await page.locator('#unlock-password').fill(password);
      await page.locator('#unlock-submit').click();
      await page.waitForFunction(() => document.documentElement.dataset.walletState === 'unlocked');
      // Browser background lock; dispatch only inside this isolated page.
      await page.evaluate(() => {Object.defineProperty(document,'hidden',{value:true,configurable:true}); document.dispatchEvent(new Event('visibilitychange'));});
      await page.waitForFunction(() => document.documentElement.dataset.walletState === 'locked');
      assert.equal(await page.locator('input[type="password"]').count(), 0);
      await page.evaluate(() => delete document.hidden);
      await page.locator('[data-nav="security"]').click();
      await page.locator('.wallets-shortcut').click();
      await page.locator('.saved-wallet > summary').first().click();
      await page.locator('[data-delete-wallet]').first().click();
      await page.locator('#confirm-remove').click();
      assert.ok(await page.evaluate(key => localStorage.getItem(key), store));
      await page.locator('#delete-confirm').fill('REMOVE');
      await page.locator('#delete-ack').check();
      await page.locator('#confirm-remove').click();
      await page.waitForFunction(() => document.documentElement.dataset.walletState === 'demo');
      assert.equal(await page.evaluate(key => localStorage.getItem(key), store), null);
      // Restore the exported encrypted file into a clean app.
      await page.locator('#security-cta').click();
      await page.locator('[data-setup="import"]').click();
      await page.locator('#backup-file').setInputFiles({name:'test-backup.json',mimeType:'application/json',buffer:Buffer.from(raw)});
      await page.waitForFunction(() => document.getElementById('file-status').textContent.startsWith('Encrypted backup'));
      await page.locator('#password').fill(password); await page.locator('#confirm').fill(password);
      await page.locator('#submit-setup').click();
      await page.waitForFunction(() => document.documentElement.dataset.walletState === 'unlocked');
      await page.locator('[data-nav=receive]').click();
      await page.locator('#receive-coin').click();await page.locator('[data-coin="wht"]').click();
      assert.equal(await page.locator('#address').textContent(), originalAddress);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      assert.deepEqual(external, []);
      assert.deepEqual(errors, []);
      console.log(`PASS ${name}: responsive preview, encrypted import/export/restore, lock, wrong password, deletion guards, QR and no external requests.`);
      await context.close();
    }
  } finally {await browser.close();}
})().catch(error => {console.error(error);process.exitCode=1;});
